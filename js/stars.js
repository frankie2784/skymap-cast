// ─── B–V colour index → RGB ───────────────────────────────────────────────────
//
// Maps the B–V colour index to a physically plausible star colour.
//
// B–V ≈ –0.4  → O/B star  → blue-white
// B–V ≈  0.0  → A star    → white
// B–V ≈  0.6  → F/G star  → yellow-white (Sun is ~0.65)
// B–V ≈  1.2  → K star    → orange
// B–V ≈  1.8  → M star    → red-orange
//
// Returns { r, g, b } in 0–1 range suitable for Three.js BufferAttribute.

function bvToColor(bv) {
  // Clamp to realistic stellar range
  const t = Math.max(-0.4, Math.min(2.0, bv));

  let r, g, b;

  if (t < 0.0) {
    // O–B: vivid blue to white-blue
    const f = (t + 0.4) / 0.4;   // 0 at bv=-0.4, 1 at bv=0.0
    r = 0.63 + 0.37 * f;
    g = 0.70 + 0.30 * f;
    b = 1.00;
  } else if (t < 0.58) {
    // A–F: white to yellowish white
    const f = t / 0.58;           // 0 at bv=0.0, 1 at bv=0.58
    r = 1.00;
    g = 1.00;
    b = 1.00 - 0.15 * f;
  } else if (t < 1.15) {
    // G–K: yellow-white to orange
    const f = (t - 0.58) / 0.57;  // 0 at bv=0.58, 1 at bv=1.15
    r = 1.00;
    g = 1.00 - 0.40 * f;
    b = 0.85 - 0.55 * f;
  } else {
    // M: orange to deep red
    const f = Math.min(1, (t - 1.15) / 0.85);  // 0 at bv=1.15, 1 at bv=2.0
    r = 1.00;
    g = 0.60 - 0.30 * f;
    b = 0.30 - 0.20 * f;
  }

  // Slightly desaturate — real stars look less vivid through atmosphere
  const desat = 0.15;
  const luma  = 0.299 * r + 0.587 * g + 0.114 * b;
  return {
    r: r * (1 - desat) + luma * desat,
    g: g * (1 - desat) + luma * desat,
    b: b * (1 - desat) + luma * desat,
  };
}

// ─── Magnitude → point size ──────────────────────────────────────────────────
//
// Converts visual magnitude to a gl_PointSize in pixels.
// Brighter stars (lower/negative magnitude) get larger points.
//
// Scale:  mag -1.5 → ~26 px,  mag 0 → ~18 px,  mag 2 → ~9 px,  mag 4 → ~4 px

function magToSize(mag) {
  // Flux is proportional to 10^(-0.4 × mag); take cube-root for visual diameter
  const flux   = Math.pow(10, -0.4 * mag);
  const refFlux= Math.pow(10, -0.4 * 0);  // magnitude-0 reference
  const scale  = Math.pow(flux / refFlux, 1 / 3);
  return Math.max(1.5, 18 * scale);
}
